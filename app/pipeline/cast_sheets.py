"""Reference sheets for supporting (non-family) characters: the wolf, the woodcutter, the
giant, the hen ... - one per story x style preset x costume (the wolf plain and in
Grandma's nightcap and shawl).

Why: a real Red book drew the wolf at wildly different sizes (a head filling the bed on
p9, twice the hero's height on p13, dog-sized on p17) because nothing gave his size and
no reference image existed (only the family had a per-book sheet). Every supporting
character now states its ``size`` relative to the hero child in the story YAML, and its
sheet shows it whole next to a plain grey height bar that marks the hero child's height
(no child is drawn - a child figure could be mistaken for the hero).

Lifecycle:

* Lazily generated by the FIRST book that needs it (``BookGenerator`` starts every sheet
  its planned pages need right away, beside the hero), stored in ``character_bible``
  (``variant_id`` "", ``costume_id`` = the costume or "") and reused by every later book of
  that story + style; ``scripts/pregenerate_assets.py`` can pre-create them with the same
  prompt. Sheets are drawn at the default detail level (like pre-generated assets), with
  the book's hero image model.
* One image call (kind ``cast_sheet``) + one vision check (kind ``cast_sheet_check``: one
  figure, right character and outfit, height bar and size). A failed check regenerates
  the sheet ONCE with the check's notes (only while the book's quality time budget is not
  used up), then keeps the sheet with fewer failed checks. A failed check CALL accepts the
  sheet unchecked; a failed image call leaves the character described in text only.
* A safety refusal of the image call (``NoImageError`` with ``finish_reason``
  PROHIBITED_CONTENT / SAFETY - the plain wolf was refused once) is retried ONCE with
  ``GENTLE_SHEET_RULE`` added (friendly cartoon, no teeth or claws); both calls recorded.
* Only with a grader (without one the book stays at one call per picture); existing
  sheets are used either way.
* Concurrency: a process-wide lock per (story, preset, character, costume) makes a second
  book wait for the first one's sheet instead of drawing its own; the insert is
  ON CONFLICT DO NOTHING (``repo_assets.insert_sheet``), so books in another process
  cannot fail on the unique key either - the loser uses the stored sheet.
"""

from __future__ import annotations

import asyncio
import logging
import time
import weakref
from collections.abc import Awaitable, Callable, Sequence

from app.pipeline.calls import CallCost, Record, short_error
from app.pipeline.prompts import cast_sheet_prompt, sheet_outfit_line
from app.providers.base import CastSheetCheck, ImageResult, NoImageError, VisionGrader
from app.stories.loader import Character, Costume, Page, Story

log = logging.getLogger("app.pipeline.cast_sheets")

CAST_SHEET_KIND = "cast_sheet"
CAST_SHEET_CHECK_KIND = "cast_sheet_check"
ImageCall = Callable[[str, int | None, str, list[bytes]], Awaitable[ImageResult]]
SheetKey = tuple[str, str]  # (character_id, costume_id); costume "" = plain


def supporting(story: Story, page: Page) -> list[Character]:
    """The page's non-family characters, in the page's order."""
    return [story.characters[c] for c in page.characters
            if c in story.characters and not story.characters[c].family]


def page_sheet_keys(story: Story, page: Page) -> list[SheetKey]:
    return [(c.id, c.sheet_costume_id(page.page)) for c in supporting(story, page)]


def needed_sheets(story: Story, pages: Sequence[Page]) -> list[SheetKey]:
    """Every (character, costume) sheet the planned pages use, in first-use order."""
    out: list[SheetKey] = []
    for p in pages:
        for key in page_sheet_keys(story, p):
            if key not in out:
                out.append(key)
    return out


def costume_label(c: Character, costume_id: str) -> str:
    """Short label for the ref line: "grandma disguise" ("" = plain)."""
    cos = c.costume(costume_id) if costume_id else None
    return cos.id.replace("_", " ") if cos else ""


_LOCKS: weakref.WeakKeyDictionary = weakref.WeakKeyDictionary()


def sheet_lock(key: tuple[str, ...]) -> asyncio.Lock:
    """Process-wide lock per sheet key (one per event loop)."""
    loop = asyncio.get_running_loop()
    locks = _LOCKS.setdefault(loop, {})
    lock = locks.get(key)
    if lock is None:
        lock = locks[key] = asyncio.Lock()
    return lock


def sheet_description(c: Character, costume: Costume | None) -> str:
    outfit = sheet_outfit_line(c, costume)
    return f"{c.description} {outfit}".strip()


async def check_cast_sheet(grader: VisionGrader, png: bytes, c: Character,
                           costume: Costume | None, record: Record) -> CastSheetCheck | None:
    """One recorded vision call; None if it failed (sheet accepted unchecked) or the
    grader cannot check sheets."""
    check = getattr(grader, "check_cast_sheet", None)
    if check is None:
        return None
    t0 = time.perf_counter()
    try:
        result = await check(png, name=c.name, description=sheet_description(c, costume),
                             size=c.size)
    except asyncio.CancelledError:
        try:
            await record(CallCost.failed(CAST_SHEET_CHECK_KIND, None, grader.model, t0,
                                         grader.name, "cancelled"))
        except Exception:
            log.exception("could not record cancelled cast sheet check")
        raise
    except Exception as exc:
        log.warning("cast sheet check failed for %s (sheet used unchecked): %s", c.id,
                    short_error(exc))
        await record(CallCost.failed(CAST_SHEET_CHECK_KIND, None, grader.model, t0,
                                     grader.name, short_error(exc)))
        return None
    await record(CallCost.of_meta(CAST_SHEET_CHECK_KIND, None, result.meta, grader.name))
    return result


def _fallback_fixes(c: Character, chk: CastSheetCheck) -> list[str]:
    out = []
    if not chk.figure_ok:
        out.append(f"draw only {c.name}, alone, whole, next to one plain grey bar - no "
                   "other figures and no scenery")
    if not chk.looks_ok:
        out.append(f"{c.name} must match the description and outfit exactly")
    if not chk.size_ok:
        out.append(f"draw the plain grey height bar and {c.name} at the stated size next to "
                   f"it: {c.size}" if c.size else "draw the plain grey height bar")
    return out


async def make_cast_sheet(image_call: ImageCall, style: str, c: Character,
                          costume: Costume | None, *, grader: VisionGrader | None = None,
                          record: Record | None = None,
                          may_retry: Callable[[], bool] | None = None,
                          ) -> tuple[ImageResult, str] | None:
    """(image, prompt) of the kept sheet, or None if the image call failed (already
    recorded by ``image_call``). Checked once with ``grader``; a failed check regenerates
    once (if ``may_retry()``), then the sheet with fewer failed checks is kept."""
    t0 = time.perf_counter()

    async def draw(corrections: Sequence[str] = ()) -> tuple[ImageResult, str] | None:
        prompt = cast_sheet_prompt(style, c, costume, corrections)
        try:
            return await image_call(CAST_SHEET_KIND, None, prompt, []), prompt
        except asyncio.CancelledError:
            raise
        except NoImageError as exc:
            if not exc.is_safety:
                log.error("cast sheet failed for %s/%s (pages describe it in text only): "
                          "%s", c.id, costume.id if costume else "plain", short_error(exc))
                return None
            # A safety refusal (PROHIBITED_CONTENT / SAFETY): ONE retry with gentler
            # wording; both calls are recorded by image_call.
            log.warning("cast sheet %s/%s refused (finish_reason=%s) - retrying once with "
                        "a gentler prompt", c.id, costume.id if costume else "plain",
                        exc.finish_reason)
            prompt = cast_sheet_prompt(style, c, costume, corrections, gentle=True)
            try:
                return await image_call(CAST_SHEET_KIND, None, prompt, []), prompt
            except asyncio.CancelledError:
                raise
            except Exception as exc2:
                log.error("cast sheet failed for %s/%s after the gentle retry (pages "
                          "describe it in text only): %s", c.id,
                          costume.id if costume else "plain", short_error(exc2))
                return None
        except Exception as exc:
            log.error("cast sheet failed for %s/%s (pages describe it in text only): %s",
                      c.id, costume.id if costume else "plain", short_error(exc))
            return None

    first = await draw()
    if first is None:
        return None
    chosen, note = first, "unchecked"
    if grader is not None and record is not None:
        chk1 = await check_cast_sheet(grader, first[0].png, c, costume, record)
        if chk1 is not None and chk1.passed:
            note = "check passed"
        elif chk1 is not None:
            log.warning("cast sheet %s failed its check: %s", c.id, chk1.issues)
            if may_retry is not None and not may_retry():
                note = "check failed, kept (no time)"
            else:
                second = await draw(chk1.issues or _fallback_fixes(c, chk1))
                if second is None:
                    note = "check failed, regeneration failed - kept the first"
                else:
                    chk2 = await check_cast_sheet(grader, second[0].png, c, costume, record)
                    if chk2 is None or chk2.passed:
                        chosen = second
                        note = "regenerated, " + ("check passed" if chk2 else "unchecked")
                    else:
                        chosen = second if chk2.failures <= chk1.failures else first
                        note = (f"failed its check twice - kept attempt "
                                f"{2 if chosen is second else 1}")
    log.info("cast sheet done character=%s costume=%s (%s) duration=%.2fs", c.id,
             costume.id if costume else "plain", note, time.perf_counter() - t0)
    return chosen
